import AppKit
import PasterCore

/// NSPasteboard → PasteboardSnapshot.
enum PasteboardReader {
    /// 건너뛸 표시가 있으면 내용은 읽지 않는다 (비밀번호 등).
    private static let skipMarkers: Set<String> = [
        PasteboardType.pasterInternal,
        PasteboardType.concealed,
        PasteboardType.transient,
        PasteboardType.autoGenerated,
    ]

    static func hasSkipMarker(_ types: [String]) -> Bool {
        !skipMarkers.isDisjoint(with: types)
    }

    /// 모든 item 의 타입.
    @MainActor
    static func types(of pasteboard: NSPasteboard) -> [String] {
        pasteboard.pasteboardItems?.flatMap { $0.types.map(\.rawValue) } ?? []
    }

    /// `readContent` 가 false 면 (제외 앱 등) 타입만 담는다.
    @MainActor
    static func snapshot(of pasteboard: NSPasteboard, readContent: Bool = true) -> PasteboardSnapshot {
        let types = types(of: pasteboard)
        guard readContent, !hasSkipMarker(types) else {
            return PasteboardSnapshot(types: types)
        }
        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        let string = pasteboard.string(forType: .string)
        var snapshot = PasteboardSnapshot(
            types: types,
            fileURLs: fileURLs,
            string: string,
            rtf: pasteboard.data(forType: .rtf),
            html: pasteboard.data(forType: .html)
        )
        // 이미지는 파일 · 텍스트가 없을 때만 읽는다 (TIFF 는 클 수 있다)
        if fileURLs.isEmpty, string?.isEmpty ?? true {
            snapshot.png = pasteboard.data(forType: .png)
            snapshot.tiff = snapshot.png == nil ? pasteboard.data(forType: .tiff) : nil
        }
        return snapshot
    }
}
